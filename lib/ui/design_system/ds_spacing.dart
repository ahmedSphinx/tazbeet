/// Design System: Spacing Constants
/// 8px base unit system for consistent spacing throughout the app
class DSSpacing {
  DSSpacing._();

  /// Extra small spacing - 4px
  /// Use for: Tight internal spacing, icon-text gaps
  static const double xs = 4.0;

  /// Small spacing - 8px (base unit)
  /// Use for: List item spacing, chip gaps, small margins
  static const double sm = 8.0;

  /// Medium spacing - 16px (2x base)
  /// Use for: Card padding, section margins, default spacing
  static const double md = 16.0;

  /// Large spacing - 24px (3x base)
  /// Use for: Section separation, major component gaps
  static const double lg = 24.0;

  /// Extra large spacing - 32px (4x base)
  /// Use for: Screen margins, large section breaks
  static const double xl = 32.0;

  /// 2X large spacing - 48px (6x base)
  /// Use for: Major layout divisions
  static const double xxl = 48.0;

  /// 3X large spacing - 64px (8x base)
  /// Use for: Hero sections, major page divisions
  static const double xxxl = 64.0;
}
